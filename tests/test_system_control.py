def test_the_list_refreshes_and_survives_a_failure():
    now, entries = [0.0], [[("Old", "1")]]

    def lister():
        if entries[0] is None:
            raise OSError("powershell failed")
        return entries[0]

    apps = InstalledApps(lister, max_age_s=10, clock=lambda: now[0])
    assert apps.find("old").name == "Old"
    entries[0], now[0] = [("New", "2")], 5.0
    assert apps.find("new").name is None  # still fresh
    now[0] = 11.0
    assert apps.find("new").name == "New"
    entries[0], now[0] = None, 22.0
    assert apps.find("new").name == "New"


