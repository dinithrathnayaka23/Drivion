# ----- carrying them out -------------------------------------------------------------------------


@pytest.fixture
def registry(installed):
    def build(desktop):
        scheduler = PowerScheduler(FakePower(), 10, False, lambda text: None)
        backends = Backends(FakeVolume(), FakeBrightness(), desktop, FakeScreen(), FakePower())
        return build_registry(backends, CommandsSettings(), ActionsSettings(), str, scheduler,
                              installed=installed)
    return build


def run(registry, intent):
    return registry.get(intent.kind).handler(intent)


def test_an_installed_app_opens_through_the_apps_folder(registry):
    desktop = FakeDesktop()
    result = run(registry(desktop), s.OpenInstalledApp(name="Spotify"))
    assert result.success and "Spotify" in result.message and not result.verified
    assert desktop.opened == [r"shell:AppsFolder\SpotifyAB.SpotifyMusic_zpdnekdrzrea0!Spotify"]


@pytest.mark.parametrize("name", ["Uninstall Node.js", "cmd /c del", "Notepad.exe & calc"])
def test_a_name_that_is_not_on_the_list_opens_nothing(registry, name):
    desktop = FakeDesktop()
    result = run(registry(desktop), s.OpenInstalledApp(name=name))
    assert not result.success and desktop.opened == []


def test_a_failed_launch_is_reported(registry):
    result = run(registry(FakeDesktop(openable=[])), s.OpenInstalledApp(name="Spotify"))
    assert not result.success and "Spotify" in result.message


def test_settings_open_their_fixed_address(registry):
    desktop = FakeDesktop()
    result = run(registry(desktop), s.OpenSettings(page="bluetooth"))
    assert result.success and result.message == "Opening Bluetooth settings."
    assert desktop.opened == ["ms-settings:bluetooth"]


def test_opening_a_surface_presses_its_shortcut(registry):
    desktop = FakeDesktop()
    result = run(registry(desktop), s.OpenSurface(surface="start_menu"))
    assert result.success and result.message == "Opening the Start menu." and desktop.surfaces == ["start_menu"]


def test_every_surface_has_a_shortcut_and_all_are_safe():
    assert set(HOTKEYS) == set(SHELL_SURFACES)
    VK_L, VK_R = 0x4C, 0x52  # Win+L locks, and Win+R opens the Run box, which runs anything
    assert all(VK_L not in keys and VK_R not in keys for keys in HOTKEYS.values())


def test_every_settings_address_is_a_settings_address():
    assert all(uri.startswith("ms-settings:") for uri, _, _ in SETTINGS_PAGES.values())


def test_only_fixed_values_validate():
    from pydantic import ValidationError

    for bad in ({"kind": "OPEN_SETTINGS", "page": "ms-settings:evil"},
                {"kind": "OPEN_SURFACE", "surface": "run_box"}):
        with pytest.raises(ValidationError):
            s.INTENT_ADAPTER.validate_python(bad)


# ----- what the AI may do ------------------------------------------------------------------------


CATALOG = Catalog.from_settings(CommandsSettings())


def test_the_ai_can_never_open_installed_apps():
    assert s.OpenInstalledApp not in LLM_ACTIONS
    with pytest.raises(ValueError, match="not allowed"):
        parse_reply('{"action": {"kind": "OPEN_INSTALLED_APP", "name": "Command Prompt"}}', CATALOG)


def test_the_ai_can_open_settings_and_surfaces():
    assert parse_reply('{"action": {"kind": "OPEN_SETTINGS", "page": "wifi"}}', CATALOG).intent.page == "wifi"
    assert parse_reply('{"action": {"kind": "OPEN_SURFACE", "surface": "start_menu"}}', CATALOG)
    assert "bluetooth" in system_prompt(CATALOG) and "start_menu" in system_prompt(CATALOG)


